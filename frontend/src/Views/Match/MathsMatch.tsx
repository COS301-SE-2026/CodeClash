import { ChevronRight, ChevronLeft } from 'lucide-react'
import { useEffect } from 'react';
import { useMatch } from 'src/ViewModels/Match/MatchViewModel';

import MathMatch from '@/components/features/Match/MathPage';
import { Question } from '@/components/features/Questions/question';
import Loading from '@/components/shared/Loading';
import { MatchScreen } from '@/components/features/Match/Match';
import { Button } from '@/components/ui/button';
import PopUp from '@/components/shared/PopUp'
import { useUser } from 'src/context/User/hooks/useUser';
import Flash from '@/components/ui/animations/Flash';
import { useState } from 'react';
import ConfirmationPopup from "../Confirmation";
import type { ConfirmationViewModel } from "src/ViewModels/ConfirmationViewModel";
import PowerEffect from "@/components/ui/animations/PowerEffect";
import { corruptMath } from 'src/utils/corrupt';
import { MatchCard } from '@/components/features/Match/MatchCard';
import { PowerUpAndDownButtons } from '@/components/features/Match/PowerUpandDownButtons';

const MathsMatch = () => {
    const {
        lastResult,
        myIndex,
        status,
        questions,
        results,
        playerLife, playerOneAvatar, playerTwoAvatar, usernames,
        seconds, minutes,
        currentQuestion, nextQuestion, prevQuestion,
        roundIdx, rounds,
        opponentCurrent, waitingOpponent, finishMatch,
        loading,
        submitQuestion,
        mathfieldRef,
        elos,
        final_question, complete_round, confirmCompleteRound, confirmRound, cancelCompleteRound, completeRound,
        matchType, matchMode, playerOneDamage, playerTwoDamage,
        powerups, activatePowerup, powerupBusy, powerupError,
        blackoutQuestionId,
        inputEffect,
        shields,
        effectProps
    } = useMatch();
    
    const roundConf: ConfirmationViewModel = {
            content: {
                title: "Complete Round?",
                message: "You won't be able to go back.",
                cancelLabel: "Cancel",
                confirmLabel: "Confirm"
            },
            isVisible: confirmRound,
            handleConfirm: completeRound,
            handleCancel: cancelCompleteRound,
        }

    const curr = questions[currentQuestion];
    const { username } = useUser();

    const correct : boolean | null = 
    results?.[roundIdx]?.[currentQuestion] ?? null;
    

    //the following block of code was copied from an older version of this file and was hand-written,
    //it was not generated by ai!

    const result_colour = () => {
        if (correct === true) return 'bg-success/50'
        else if (correct === false) return 'bg-danger/50'
        else return 'bg-card-tournament'
    }

    const result_border = () => {
        if(correct === true) return "border border-success"
        else if (correct === false) return "border border-danger"
        else return ""
    }

    const [flashTrigger, setFlashTrigger] = useState(0);

    useEffect(() => {
        if(correct !== null) {
            setFlashTrigger(t => t + 1);
        }
    }, [lastResult, currentQuestion, roundIdx, correct]);

    const myLife = myIndex >= 0 ? playerLife[myIndex] : undefined;
    const lowLife = myLife !== undefined && myLife >= 0 && myLife <= 25;

    /////////////////////////////////////////////////////////////////


    useEffect(() => {
        if (mathfieldRef.current) {
            mathfieldRef.current.value = '';
        }
    }, [currentQuestion])

    useEffect(() => {
        const mf = mathfieldRef.current;
        if (!inputEffect || !mf) return;
        mf.value = inputEffect.kind === 'clear' ? '' : corruptMath(mf.value);
    }, [inputEffect]);

    if (status !== 'ready' || !curr) {
        return (
            <Loading isOpen={loading || status !== 'ready' || !curr}></Loading>
        )
    }

    return (
        <MatchScreen
            player_life={playerLife}
            seconds={seconds}
            minutes={minutes}
            playerOneAvatar={playerOneAvatar}
            playerTwoAvatar={playerTwoAvatar}
            usernames={usernames}
            elos={elos}
            current_question={currentQuestion}
            opponent_progress={opponentCurrent}
            question_number={questions.length}
            question_results={results ?? []}
            rounds={rounds}
            current_round={roundIdx}
            current_user={username}
            playerOneDamage={playerOneDamage}
            playerTwoDamage={playerTwoDamage}
            shields={shields}
            powerups={powerups}
            onUsePowerup={activatePowerup}
            powerupBusy={powerupBusy}
            powerupError={powerupError}
        >

            {/* the following line of code was copied and pasted from another version of this file and was not generated by ai!!! */}
            {lowLife && <div className="danger-pulse pointer-events-none fixed inset-0 z-40"/>}

            { curr.id === blackoutQuestionId ? (
                <MatchCard className='h-[20rem] flex items-center justify-center text-xl font-semibold text-muted-text'>
                    Question blacked out
                </MatchCard>
            ) : (<Question
                className={``}
                difficulty={curr.difficulty!}
                title={curr.title!}
                description={curr.description}
            />)}

            <div className={`w-[100%] flex items-center justify-center`}>
                <Flash
                    result={correct ?? null}
                    trigger={flashTrigger}
                    className="w-[100%] flex flex-col items-center justify-center mt-5 rounded-2xl">

                
                    <MathMatch
                        mathfieldRef={mathfieldRef}
                        className={`${result_colour()} ${result_border()}`}
                    >

                    </MathMatch>
                </Flash>
            </div>
            <div className='w-[100%] h-[6rem] flex flex-row flex-shrink-0 items-center justify-evenly rounded-4xl relative'>

                <div className='flex items-center justify-evenly text-secondary bg-primary rounded-2xl w-[15%]'>
                    <ChevronLeft onClick={() => prevQuestion(currentQuestion)} className='size-[3rem] hover:scale-110  hover:bg-secondary/20 rounded-2xl w-[50%]' />
                    <ChevronRight onClick={() => nextQuestion(currentQuestion)} className='size-[3rem] hover:scale-110 hover:bg-secondary/20 rounded-2xl w-[50%]' />
                </div>
                <Button className='w-[20%] h-[2.6rem] rounded-2xl text-[1rem] hover:-translate-y-1'
                    onClick={async () => {
                        const answer = mathfieldRef.current?.value ?? '';
                        await submitQuestion({ answer: answer }, matchType!,matchMode! )
                    }}
                >
                    Submit Answer
                </Button>
                {final_question ? (

                    <Button className='w-[20%] h-[2.6rem] rounded-2xl text-[1rem] hover:-translate-y-1'
                        onClick={async () => { await finishMatch(); }}
                    >
                        <p>Finish Match</p>
                    </Button>) :
                    complete_round && (
                        <Button className='w-[20%] h-[2.6rem] rounded-2xl text-[1rem] hover:-translate-y-1'
                            onClick={() => { confirmCompleteRound() }}
                        >
                            <p>Complete Round</p>
                        </Button>
                    )
                }

                {
                    confirmRound && (
                        <ConfirmationPopup confirmation={roundConf}/>
                    )
                }

                <PowerUpAndDownButtons>
                    {/* the code below was copied and pasted from Match.tsx, it was my teammate's code that I am refactoring
                    it is not a product of ai! */}
                    {(powerups ?? []).length === 0 && <p className="text-xs text-muted-text">No Powerups</p>}
                        {(powerups ?? []).map(p => (
                            <button
                            key={p.shop_item_id}
                            title={p.description}
                            disabled={powerupBusy}
                            onClick={() => activatePowerup?.(p.shop_item_id)}
                            className={`w-full text-xs rounded-lg py-1 hover:bg-secondary/20 disabled:opacity-50 ${p.kind === 'powerdown' ? 'text-danger' : 'text-success'}`}
                            >
                                {p.name} ×{p.quantity}
                            </button>
                        ))}
                    {powerupError && <p className='text-danger text=[0.7rem] tet-center'>{powerupError}</p>}
                </PowerUpAndDownButtons>


            </div>


            {waitingOpponent && (
                <PopUp
                    isOpen={waitingOpponent}
                    title={'Waiting For Opponent To Finish'}
                    subtitle={'Hang on while your opponent finishes up'}
                />
            )

            }
            <PowerEffect {...effectProps}/>
        </MatchScreen >
    )

}

export default MathsMatch;