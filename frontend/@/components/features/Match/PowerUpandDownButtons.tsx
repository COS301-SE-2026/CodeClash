import "../../../../src/styles/global.css"
import React from "react"
import { Button } from "@/components/ui/button";
import { ChevronDown, ChevronUp } from "lucide-react";
import { useState, useEffect } from "react";

export interface PowerupItem {
    shop_item_id: string;
    name: string; 
    description?: string;
    kind: 'powerup' | 'powerdown'
    quantity: number
}

interface PowerUpAndDownButtonsProps {
    powerups: PowerupItem[];
    onUse: (shop_item_id: string) => void | Promise<void>;
    busy?: boolean
    error?: string | null
    closeOnUse?: boolean
    children?: React.ReactNode;
    className?: string;
}


export const PowerUpAndDownButtons = ({powerups, onUse, busy = false, error, closeOnUse = true, children, className} : PowerUpAndDownButtonsProps) => {
    //the code below was copied from another file that was overwritten when merged (it was saved before merging),
    //all this pasted code was hand-written and not generated by ai

    const [filter, setFilter] = useState<'powerup' | 'powerdown' | null>(null);
    // const { usePowerups } = useMatch();

    const close = () => setFilter(null);
    const items = filter ? powerups.filter(p => p.kind === filter) : []

    useEffect(() => {
        if (!filter) return
        const onKey = (e: KeyboardEvent) => e.key === 'Escape' && close()
        window.addEventListener('keydown', onKey)
        return () => window.removeEventListener('keydown', onKey)
    }, [filter])

    const handleUse = async (id: string) => {
        await onUse(id)
        if (closeOnUse){
            close()
        }
    }

    const category = filter === 'powerup' ? 'Powerups' : 'PowerDowns'


    return(
        <div className={`flex flex-row gap-5 bg-background-elevated border border-border rounded-3xl py-2 px-2 h-[70%] ${className}`}>
                <Button className="card-elevated h-11 w-30 rounded-full my-auto" onClick={() => setFilter('powerup')}>
                    <div className="flex flex-row">
                        <ChevronUp className="text-[var(--match-box)] size-6.5"/>
                        <h1 className="text-[1rem] text-[var(--match-box)] font-semibold my-auto mx-auto">Powerups</h1>
                    </div>
                </Button>

                <Button className="card-elevated h-11 w-31 rounded-full my-auto" onClick={() => setFilter('powerdown')}>
                    <div className="flex flex-row">
                        <ChevronDown className="text-[var(--match-box)] size-6.5"/>
                        <h1 className="text-[0.9rem] text-[var(--match-box)] font-semibold my-auto">Powerdowns</h1>
                    </div>
                </Button>

                {children}

            </div>
    );

}