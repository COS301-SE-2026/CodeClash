import "../../../../src/styles/global.css"
import React from "react"
import { Button } from "@/components/ui/button";
import { ChevronDown, ChevronUp, X } from "lucide-react";
import { useState, useEffect } from "react";
import {createPortal} from "react-dom"
import { cn } from "@/lib/utils";

export interface PowerupItem {
    shop_item_id: string;
    name: string; 
    description?: string;
    kind: 'powerup' | 'powerdown'
    quantity: number
}

interface PowerUpAndDownButtonsProps {
    powerups: PowerupItem[];
    onUse: (shop_item_id: string) => void | Promise<void>;
    busy?: boolean
    error?: string | null
    closeOnUse?: boolean
    children?: React.ReactNode;
    className?: string;
}


export const PowerUpAndDownButtons = ({powerups, onUse, busy = false, error, closeOnUse = true, children, className} : PowerUpAndDownButtonsProps) => {
    //the code below was copied from another file that was overwritten when merged (it was saved before merging),
    //all this pasted code was hand-written and not generated by ai

    const [filter, setFilter] = useState<'powerup' | 'powerdown' | null>(null);
    // const { usePowerups } = useMatch();

    const close = () => setFilter(null);
    const items = filter ? powerups.filter(p => p.kind === filter) : []

    useEffect(() => {
        if (!filter) return
        const onKey = (e: KeyboardEvent) => e.key === 'Escape' && close()
        window.addEventListener('keydown', onKey)
        return () => window.removeEventListener('keydown', onKey)
    }, [filter])

    const handleUse = async (id: string) => {
        await onUse(id)
        if (closeOnUse){
            close()
        }
    }

    const category = filter === 'powerup' ? 'Powerups' : 'PowerDowns'


    return(
        <>
        <div className={`flex flex-row gap-5 bg-background-elevated border border-border rounded-3xl py-2 px-2 h-[70%] ${className}`}>
                <Button className="card-elevated h-11 w-30 rounded-full my-auto" onClick={() => setFilter('powerup')}>
                    <div className="flex flex-row">
                        <ChevronUp className="text-[var(--match-box)] size-6.5"/>
                        <h1 className="text-[1rem] text-[var(--match-box)] font-semibold my-auto mx-auto">Powerups</h1>
                    </div>
                </Button>

                <Button className="card-elevated h-11 w-31 rounded-full my-auto" onClick={() => setFilter('powerdown')}>
                    <div className="flex flex-row">
                        <ChevronDown className="text-[var(--match-box)] size-6.5"/>
                        <h1 className="text-[0.9rem] text-[var(--match-box)] font-semibold my-auto">Powerdowns</h1>
                    </div>
                </Button>


            </div>

            {filter && createPortal(
                <div
                    className="fixed inset-0 z-50 flex items-center justify-center bg-black/60" onClick={close}
                >
                    <div
                        role="dialog"
                        aria-label={category}
                        className="w-[22rem] max-h-[70vh] flex flex-col gap-3 rounded-xl border border-border bg-background-elevated p-5 shadow-xl">
                    
                        <div className="flex items-center justify-between">
                            <h2 className="text-lg font-semibold">{category}</h2>
                            <button onClick={close} aria-label="Close" className="rounded-full p-1 hover:bg-secondary/20">
                                <X size={20}/>
                            </button>
                        </div>

                        <div className="flex flex-col gap-2 overflow-y-auto">
                            {items.length === 0 && (
                                <p className="text-sm text-muted-text text-center py-4">
                                    No {category} owned
                                </p>
                            )}

                            {items.map(p => (
                                <button
                                    key={p.shop_item_id}
                                    title={p.description}
                                    disabled={busy || p.quantity <= 0}
                                    onClick={() => handleUse(p.shop_item_id)}
                                    className={cn("w-full text-sm rounded-xl py-2 px-3 flex justify-between border border-border hover:bg-secondary/20 disabled:opacity-50", p.kind === 'powerdown' ? 'text-danger' : 'text-success')}
                                    >
                                        <span>{p.name}</span>
                                        <span>×{p.quantity}</span>

                                </button>
                            ))}
                        </div>
                        
                        {error && <p className="text-danger text-xs text-center">{error}</p>}

                    </div>
                    {children}
                </div>,
                document.body
            )}

        </>
    )
}